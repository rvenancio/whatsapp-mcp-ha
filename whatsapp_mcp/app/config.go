// Authentication methods. api_key is the default and the only one that uses the add-on bearer tokens.
const (
	AuthMethodAPIKey = "api_key" // auth_token (read) and send_token (send)
	AuthMethodNone   = "none"    // no authentication; not recommended
)

// MinTokenLength is the minimum length of a user-provided bearer token.
const MinTokenLength = 32

// MinTokenDistinct is the minimum number of different characters in a user-provided token.
const MinTokenDistinct = 10

// isRepetitive reports tokens made of a short repeated pattern (e.g. "abcabcabc…").
func isRepetitive(s string) bool {
	for period := 1; period <= 8 && period < len(s); period++ {
		rep := true
		for i := period; i < len(s); i++ {
			if s[i] != s[i-period] {
				rep = false
				break
			}
		}
		if rep {
			return true
		}
	}
	return false
}

// Config is the runtime configuration. In the Home Assistant add-on it comes from
// /data/options.json; for a plain Docker run it comes from WA_MCP_* environment variables.
type Config struct {
	AuthToken      string // read-only token: the read tools only
	TokenGenerated bool   // true when the token was generated by the add-on (shown on the add-on page)
	// SendToken is the only token that can list and call the send tools, and only when EnableSend is on.
	// It also gets the read tools. With EnableSend on and no send_token configured, one is generated.
	SendToken          string
	SendTokenGenerated bool // true when the send token was generated by the add-on
	EnableSend         bool
	// sendActive is fixed at startup (LoadConfig / EnsureSendToken) and never changes afterwards, so request
	// handlers can read it without locking while the page rotates tokens.
	sendActive bool
	// InactiveSendToken is a send token that exists (configured, or generated earlier) while enable_send is off.
	// It is not accepted, but a request carrying it is not counted as a failed login either.
	InactiveSendToken  string
	SendPerMinute      int
	SendPerDay         int
	AllowMediaDownload bool
	MaxMediaMB         int
	LogLevel           slog.Level
	// AllowedRecipients are the only chats the send tools may write to (canonical JIDs). Empty refuses every send.
	AllowedRecipients map[string]bool
	// RetentionDays deletes stored messages older than this many days; 0 keeps everything.
	RetentionDays int

	DataDir  string // whatsmeow session and message database
	MediaDir string // outbox/ (files that may be sent) and downloads/
	Listen   string // MCP endpoint, exposed
	// PageListen is the pairing page (Home Assistant ingress). Empty disables it.
	PageListen string
	// PageAllowedIPs are the only client addresses allowed on the pairing page
	// (the Home Assistant ingress proxy).
	PageAllowedIPs []net.IP
	AddonMode      bool

	// AuthMethod is none or api_key (default).
	AuthMethod string
}

type addonOptions struct {
	AuthToken          *string  `json:"auth_token"`
	SendToken          *string  `json:"send_token"`
	EnableSend         *bool    `json:"enable_send"`
	SendPerMinute      *int     `json:"send_rate_per_minute"`
	SendPerDay         *int     `json:"send_daily_limit"`
	AllowMediaDownload *bool    `json:"allow_media_download"`
	MaxMediaMB         *int     `json:"max_media_mb"`
	LogLevel           *string  `json:"log_level"`
	AllowedRecipients  []string `json:"allowed_recipients"`
	RetentionDays      *int     `json:"retention_days"`
	AuthMethod         *string  `json:"auth_method"`
}

// LoadConfig reads options.json if present, otherwise the environment.
func LoadConfig(optionsPath string, getenv func(string) string) (*Config, error) {
	cfg := &Config{
		EnableSend:     false,
		SendPerMinute:  6,
		SendPerDay:     50,
		MaxMediaMB:     16,
		LogLevel:       slog.LevelInfo,
		DataDir:        "/data",
		MediaDir:       "/share/whatsapp-mcp",
		Listen:         ":8120",
		PageAllowedIPs: []net.IP{net.ParseIP("172.30.32.2")},
	}
	var opts addonOptions
	raw, err := os.ReadFile(optionsPath)
	switch {
	case err == nil:
		if err := json.Unmarshal(raw, &opts); err != nil {
			return nil, fmt.Errorf("invalid %s: %w", optionsPath, err)
		}
		cfg.AddonMode = true
		cfg.PageListen = ":8121"
	case errors.Is(err, os.ErrNotExist):
		if err := optionsFromEnv(&opts, getenv); err != nil {
			return nil, err
		}
	default:
		return nil, fmt.Errorf("read %s: %w", optionsPath, err)
	}
	if opts.AuthToken != nil {
		cfg.AuthToken = strings.TrimSpace(*opts.AuthToken)
	}
	if opts.SendToken != nil {
		cfg.SendToken = strings.TrimSpace(*opts.SendToken)
	}
	if opts.EnableSend != nil {
		cfg.EnableSend = *opts.EnableSend
	}
	if opts.SendPerMinute != nil {
		cfg.SendPerMinute = *opts.SendPerMinute
	}
	if opts.SendPerDay != nil {
		cfg.SendPerDay = *opts.SendPerDay
	}
	if opts.AllowMediaDownload != nil {
		cfg.AllowMediaDownload = *opts.AllowMediaDownload
	}
	if opts.MaxMediaMB != nil {
		cfg.MaxMediaMB = *opts.MaxMediaMB
	}
	if opts.RetentionDays != nil {
		cfg.RetentionDays = *opts.RetentionDays
	}
	if opts.AuthMethod != nil {
		cfg.AuthMethod = strings.TrimSpace(*opts.AuthMethod)
	}
	for i, r := range opts.AllowedRecipients {
		if strings.TrimSpace(r) == "" {
			continue
		}
		jid, err := ParseRecipient(r)
		if err != nil {
			// The entry itself is not repeated: it may be someone's phone number.
			return nil, fmt.Errorf("allowed_recipients: entry %d: %w", i+1, err)
		}
		if cfg.AllowedRecipients == nil {
			cfg.AllowedRecipients = map[string]bool{}
		}
		cfg.AllowedRecipients[jid.String()] = true
	}
	if opts.LogLevel != nil {
		lvl, err := parseLevel(*opts.LogLevel)
		if err != nil {
			return nil, err
		}
		cfg.LogLevel = lvl
	}
	// Paths and listeners can be overridden in both modes (tests, Docker).
	if v := getenv("WA_MCP_DATA_DIR"); v != "" {
		cfg.DataDir = v
	}
	if v := getenv("WA_MCP_MEDIA_DIR"); v != "" {
		cfg.MediaDir = v
	}
	if v := getenv("WA_MCP_LISTEN"); v != "" {
		cfg.Listen = v
	}
	if v, ok := lookup(getenv, "WA_MCP_PAGE_LISTEN"); ok {
		cfg.PageListen = v
	}
	if v := getenv("WA_MCP_PAGE_ALLOWED_IPS"); v != "" {
		cfg.PageAllowedIPs = nil
		for _, s := range strings.Split(v, ",") {
			ip := net.ParseIP(strings.TrimSpace(s))
			if ip == nil {
				return nil, fmt.Errorf("WA_MCP_PAGE_ALLOWED_IPS: invalid address %q", s)
			}
			cfg.PageAllowedIPs = append(cfg.PageAllowedIPs, ip)
		}
	}
	if err := cfg.validate(); err != nil {
		return nil, err
	}
	cfg.finishSend()
	return cfg, nil
}

// finishSend fixes whether sending is active. Called once the tokens are final.
func (c *Config) finishSend() {
	if c.AuthMethod == AuthMethodNone {
		// No bearer token distinguishes readers from senders. enable_send is the switch, and
		// allowed_recipients still refuses every send when it is empty.
		c.sendActive = c.EnableSend
		c.InactiveSendToken = ""
		return
	}
	c.sendActive = c.EnableSend && c.SendToken != ""
	c.InactiveSendToken = ""
	if !c.EnableSend && c.SendToken != "" {
		c.InactiveSendToken = c.SendToken
	}
}

// lookup treats the literal value "off" as an explicit empty value.
func lookup(getenv func(string) string, key string) (string, bool) {
	v := getenv(key)
	if v == "" {
		return "", false
	}
	if v == "off" {
		return "", true
	}
	return v, true
}

func optionsFromEnv(o *addonOptions, getenv func(string) string) error {
	if v := getenv("WA_MCP_TOKEN"); v != "" {
		o.AuthToken = &v
	}
	if v := getenv("WA_MCP_SEND_TOKEN"); v != "" {
		o.SendToken = &v
	}
	for key, dst := range map[string]**bool{
		"WA_MCP_ENABLE_SEND":          &o.EnableSend,
		"WA_MCP_ALLOW_MEDIA_DOWNLOAD": &o.AllowMediaDownload,
	} {
		if v := getenv(key); v != "" {
			b, err := strconv.ParseBool(v)
			if err != nil {
				return fmt.Errorf("%s: %w", key, err)
			}
			*dst = &b
		}
	}
	for key, dst := range map[string]**int{
		"WA_MCP_SEND_RATE_PER_MINUTE": &o.SendPerMinute,
		"WA_MCP_SEND_DAILY_LIMIT":     &o.SendPerDay,
		"WA_MCP_MAX_MEDIA_MB":         &o.MaxMediaMB,
	} {
		if v := getenv(key); v != "" {
			n, err := strconv.Atoi(v)
			if err != nil {
				return fmt.Errorf("%s: %w", key, err)
			}
			*dst = &n
		}
	}
	if v := getenv("WA_MCP_LOG_LEVEL"); v != "" {
		o.LogLevel = &v
	}
	if v := getenv("WA_MCP_ALLOWED_RECIPIENTS"); v != "" {
		o.AllowedRecipients = strings.Split(v, ",")
	}
	if v := getenv("WA_MCP_RETENTION_DAYS"); v != "" {
		n, err := strconv.Atoi(v)
		if err != nil {
			return fmt.Errorf("WA_MCP_RETENTION_DAYS: %w", err)
		}
		o.RetentionDays = &n
	}
	if v := getenv("WA_MCP_AUTH_METHOD"); v != "" {
		o.AuthMethod = &v
	}
	return nil
}

func parseLevel(s string) (slog.Level, error) {
	switch strings.ToLower(s) {
	case "debug":
		return slog.LevelDebug, nil
	case "info", "":
		return slog.LevelInfo, nil
	case "warning", "warn":
		return slog.LevelWarn, nil
	case "error":
		return slog.LevelError, nil
	}
	return 0, fmt.Errorf("log_level: unknown level %q", s)
}

// validateToken applies the strength rules to a user-provided token.
func validateToken(name, tok string) error {
	if len(tok) < MinTokenLength {
		return fmt.Errorf("%s must be at least %d characters", name, MinTokenLength)
	}
	distinct := map[rune]bool{}
	for _, r := range tok {
		if r <= ' ' || r > '~' {
			return fmt.Errorf("%s may only contain printable ASCII characters without spaces", name)
		}
		distinct[r] = true
	}
	if len(distinct) < MinTokenDistinct || isRepetitive(tok) {
		return fmt.Errorf("%s is too predictable: use a random value, e.g. from 'openssl rand -base64 32'", name)
	}
	return nil
}

func (c *Config) validate() error {
	if err := c.normalizeAuth(); err != nil {
		return err
	}
	if c.usesAPIKey() {
		if c.AuthToken != "" {
			if err := validateToken("auth_token", c.AuthToken); err != nil {
				if len(c.AuthToken) < MinTokenLength {
					return fmt.Errorf("%w (leave it empty to generate one)", err)
				}
				return err
			}
		}
		if c.SendToken != "" {
			if err := validateToken("send_token", c.SendToken); err != nil {
				return err
			}
		}
		if err := c.checkDistinctTokens(); err != nil {
			return err
		}
	}
	if c.SendPerMinute < 1 || c.SendPerMinute > 60 {
		return errors.New("send_rate_per_minute must be between 1 and 60")
	}
	if c.SendPerDay < 1 || c.SendPerDay > 10000 {
		return errors.New("send_daily_limit must be between 1 and 10000")
	}
	if c.RetentionDays < 0 || c.RetentionDays > 3650 {
		return errors.New("retention_days must be between 0 (keep) and 3650")
	}
	if c.MaxMediaMB < 1 || c.MaxMediaMB > 100 {
		return errors.New("max_media_mb must be between 1 and 100")
	}
	if c.Listen == "" {
		return errors.New("the MCP listen address cannot be empty")
	}
	return nil
}

// usesAPIKey reports whether bearer tokens are the authentication method.
// An empty method is api_key, so callers that build a Config without LoadConfig keep the old behaviour.
func (c *Config) usesAPIKey() bool {
	return c.AuthMethod == "" || c.AuthMethod == AuthMethodAPIKey
}

// normalizeAuth canonicalises auth_method.
func (c *Config) normalizeAuth() error {
	switch strings.ToLower(strings.TrimSpace(c.AuthMethod)) {
	case "", "api_key", "api-key", "apikey":
		c.AuthMethod = AuthMethodAPIKey
	case "none":
		c.AuthMethod = AuthMethodNone
	default:
		return fmt.Errorf("auth_method: unknown value %q (use none or api_key)", c.AuthMethod)
	}
	return nil
}

// checkDistinctTokens refuses a send_token equal to the read-only token: one token would then grant both.
// It runs again after a generated read-only token is loaded.
func (c *Config) checkDistinctTokens() error {
	if c.SendToken != "" && c.AuthToken != "" && subtle.ConstantTimeCompare([]byte(c.SendToken), []byte(c.AuthToken)) == 1 {
		return errors.New("send_token must be different from auth_token")
	}
	return nil
}

// SendActive reports whether the send tools are available: enable_send is on and a send token exists
// (configured, or generated by EnsureSendToken).
func (c *Config) SendActive() bool { return c.sendActive }

// OutboxDir is the only directory send_file / send_audio_message may read from.
func (c *Config) OutboxDir() string { return filepath.Join(c.MediaDir, "outbox") }

// DownloadDir is where download_media writes files.
func (c *Config) DownloadDir() string { return filepath.Join(c.MediaDir, "downloads") }

func (c *Config) MaxMediaBytes() int64 { return int64(c.MaxMediaMB) << 20 }

// Generated token files in the data folder. The "shown" marker records that the page revealed the token.
const (
	authTokenFile      = "auth_token"
	tokenShownFile     = "auth_token_shown"
	sendTokenFile      = "send_token"
	sendTokenShownFile = "send_token_shown"
)

// EnsureToken loads or creates the generated read-only token when none is configured.
// The token is never logged.
func (c *Config) EnsureToken() error {
	if !c.usesAPIKey() {
		return nil
	}
	if c.AuthToken != "" {
		return c.checkDistinctTokens()
	}
	tok, err := loadOrGenerate(c.DataDir, authTokenFile, tokenShownFile, c.SendToken)
	if err != nil {
		return err
	}
	c.AuthToken, c.TokenGenerated = tok, true
	return c.checkDistinctTokens()
}

// EnsureSendToken loads or creates the generated send token when enable_send is on and no send_token is
// configured. With enable_send off nothing is generated and the send token is not accepted.
// It also fixes SendActive for the rest of the run.
func (c *Config) EnsureSendToken() error {
	if err := c.ensureSendToken(); err != nil {
		return err
	}
	c.finishSend()
	if c.usesAPIKey() && !c.EnableSend && c.SendToken == "" {
		// A send token generated while sending was on: not accepted now, but not a failed login either.
		if raw, err := os.ReadFile(filepath.Join(c.DataDir, sendTokenFile)); err == nil {
			if tok := strings.TrimSpace(string(raw)); len(tok) >= MinTokenLength && tok != c.AuthToken {
				c.InactiveSendToken = tok
			}
		}
	}
	return nil
}

func (c *Config) ensureSendToken() error {
	if !c.usesAPIKey() {
		return nil
	}
	if !c.EnableSend || c.SendToken != "" {
		return c.checkDistinctTokens()
	}
	tok, err := loadOrGenerate(c.DataDir, sendTokenFile, sendTokenShownFile, c.AuthToken)
	if err != nil {
		return err
	}
	c.SendToken, c.SendTokenGenerated = tok, true
	return c.checkDistinctTokens()
}

// loadOrGenerate returns the token stored in dataDir/file, or generates one. A stored token equal to
// other (the other token) is replaced.
func loadOrGenerate(dataDir, file, shownFile, other string) (string, error) {
	path := filepath.Join(dataDir, file)
	if raw, err := os.ReadFile(path); err == nil {
		tok := strings.TrimSpace(string(raw))
		if len(tok) >= MinTokenLength && tok != other {
			return tok, nil
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("read generated token: %w", err)
	}
	return generateTokenFile(dataDir, file, shownFile)
}

// GenerateToken creates a new read-only token in dataDir/auth_token (0600) and clears the "shown" marker.
func GenerateToken(dataDir string) (string, error) {
	return generateTokenFile(dataDir, authTokenFile, tokenShownFile)
}

// GenerateSendToken creates a new send token in dataDir/send_token (0600) and clears its "shown" marker.
func GenerateSendToken(dataDir string) (string, error) {
	return generateTokenFile(dataDir, sendTokenFile, sendTokenShownFile)
}

// generateTokenFile writes a 256-bit token to dataDir/file (0600) and clears the "shown" marker.
func generateTokenFile(dataDir, file, shownFile string) (string, error) {
	buf := make([]byte, 32)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	tok := base64.RawURLEncoding.EncodeToString(buf)
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return "", err
	}
	tmp := filepath.Join(dataDir, file+".tmp")
	if err := os.WriteFile(tmp, []byte(tok+"\n"), 0o600); err != nil {
		return "", fmt.Errorf("store generated token: %w", err)
	}
	if err := os.Rename(tmp, filepath.Join(dataDir, file)); err != nil {
		return "", fmt.Errorf("store generated token: %w", err)
	}
	_ = os.Remove(filepath.Join(dataDir, shownFile))
	return tok, nil
}
